#!/usr/bin/env python3
"""Writes platform/keycloak/realm-import.yaml from deploy/keycloak/pagerewind-realm.json.

The realm file is the single source: the Compose quickstart and the tests import it directly, and the
cluster imports it through this KeycloakRealmImport. Placeholders such as ${NOTIFY_CLIENT_SECRET} are
filled by Keycloak from the Secret keycloak-clients (created by scripts/demo/keycloak-secrets.ps1).

    python scripts/render-realm-import.py          # write the file
    python scripts/render-realm-import.py --check  # fail if the file is out of date (CI)
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REALM = ROOT / "deploy" / "keycloak" / "pagerewind-realm.json"
OUTPUT = ROOT / "platform" / "keycloak" / "realm-import.yaml"
SECRET = "keycloak-clients"


def render() -> str:
    text = REALM.read_text(encoding="utf-8")
    realm = json.loads(text)
    names = sorted(set(re.findall(r"\$\{([A-Z0-9_]+)\}", text)))
    lines = [
        "# Generated by scripts/render-realm-import.py from deploy/keycloak/pagerewind-realm.json. Do not edit.",
        "# Keycloak imports the realm once; later changes to an existing realm are made in Keycloak itself.",
        "apiVersion: k8s.keycloak.org/v2beta1",
        "kind: KeycloakRealmImport",
        "metadata:",
        "  name: pagerewind",
        "spec:",
        "  keycloakCRName: keycloak",
        "  placeholders:",
    ]
    for name in names:
        lines += [
            f"    {name}:",
            "      secret:",
            f"        name: {SECRET}",
            f"        key: {name}",
        ]
    lines.append("  realm:")
    lines += ["    " + line for line in json.dumps(realm, indent=2).splitlines()]
    return "\n".join(lines) + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date. Run: python scripts/render-realm-import.py")
            return 1
        print("realm-import.yaml is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
